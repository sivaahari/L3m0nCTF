"""Golden tests for the Scoreboard view-model builder (SP6 Stream C).

Compares `build_scoreboard_view` outputs with the canonical golden fixtures generated by
L3m0nCTF-ui (tools/dump-golden-scoreboard.mjs).
"""
import json
import os

import pytest

from CTFd.plugins.l3mon_theme.pages.scoreboard import build_scoreboard_view

FIXTURES_PATH = os.path.join(os.path.dirname(__file__), "fixtures", "golden_scoreboard.json")


def load_fixtures():
    with open(FIXTURES_PATH, "r", encoding="utf-8") as f:
        return json.load(f)


FIXTURES = load_fixtures()


@pytest.mark.parametrize("name", sorted(FIXTURES.keys()))
def test_golden_scoreboard_view_model(name):
    scenario = FIXTURES[name]
    inp = scenario["input"]
    expected = scenario["expected"]

    actual = build_scoreboard_view(
        data=inp["data"],
        rows_html=inp["rows_html"],
    )

    assert actual == expected, f"Scoreboard view model mismatch in scenario: {name}"
